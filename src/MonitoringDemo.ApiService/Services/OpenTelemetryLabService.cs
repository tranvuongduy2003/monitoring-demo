        new("OpenTelemetry SDK", "Providers + processors", "The SDK samples, batches, aggregates, and owns export pipelines."),
        new("OTLP / Prometheus", "Export", "OTLP pushes logs and traces; Prometheus scrapes metrics."),
        new("Backends", "Analyze", "Tempo, Loki, Prometheus, Grafana, and Aspire store or visualize signals.")
    ];

    private static readonly IReadOnlyList<OpenTelemetryConceptItem> ApiAndSdk =
    [
        new("API", "Stable instrumentation surface", "ActivitySource, Meter, ILogger", "Application and library code creates telemetry here."),
        new("SDK", "Configurable implementation", "TracerProvider, MeterProvider, LoggerProvider", "The host configures sampling, processing, resources, readers, and exporters.")
    ];

    private static readonly IReadOnlyList<OpenTelemetryInstrumentationItem> Instrumentation =
    [
        new("Automatic", "ASP.NET Core", "Incoming HTTP spans and request duration metrics", true),
        new("Automatic", "HttpClient", "Outgoing HTTP client spans and metrics", true),
        new("Automatic", ".NET runtime", "GC, heap, thread-pool, and process metrics", true),
        new("Manual", TelemetryConstants.ActivitySourceName, "Business spans, attributes, events, and status", true),
        new("Manual", TelemetryConstants.MeterName, "Counters, histograms, and observable gauges", true),
        new("Manual", "Microsoft.Extensions.Logging", "Structured logs correlated to the active trace", true)
    ];

    private static readonly IReadOnlyList<OpenTelemetryConceptItem> SemanticConventions =
    [
        new("HTTP", "http.request.method", "GET | POST | PUT", "Standard attribute for the request method."),
        new("URL", "url.path", "/demo/checkout", "Standard low-cardinality request path."),
        new("Server", "server.address", "monitoring-demo", "Logical server host handling the request."),
        new("Response", "http.response.status_code", "200 | 500", "Standard numeric HTTP response status."),
        new("Custom", "demo.operation", "checkout | catalog | payment | fulfillment", "Namespaced, bounded domain-specific attribute.")
    ];

    private static readonly IReadOnlyList<OpenTelemetrySignalComponent> SignalComponents =
    [
        new("Tracer", "ActivitySource", "Spans", "Tempo + Aspire", "Records causal operations, timing, attributes, events, and status."),
        new("Meter", "System.Diagnostics.Metrics.Meter", "Metric points", "Prometheus + Aspire", "Records aggregatable counters, histograms, and observable gauges."),
        new("Logger", "Microsoft.Extensions.Logging", "Log records", "Loki or Aspire", "Records structured events with active trace and span correlation.")
    ];

    private static readonly IReadOnlyList<OpenTelemetryPropagatorItem> Propagators =
    [
        new("W3C Trace Context", "traceparent", "Carries trace ID, parent span ID, and sampling flags.", true),
        new("W3C Trace Context", "tracestate", "Carries ordered vendor-specific trace state.", true),
        new("W3C Baggage", "baggage", "Carries selected application context separately from span attributes.", true)
    ];
}

public sealed class OpenTelemetrySeedService : BackgroundService
{
    private readonly OpenTelemetryLabService _lab;

    public OpenTelemetrySeedService(OpenTelemetryLabService lab) => _lab = lab;

    protected override async Task ExecuteAsync(CancellationToken stoppingToken)
    {
        try
        {
            await Task.Delay(TimeSpan.FromSeconds(4), stoppingToken);
            _lab.Seed(80);
        }
        catch (OperationCanceledException) when (stoppingToken.IsCancellationRequested)
        {
            // Normal shutdown before the teaching dataset is created.
        }
    }
}

