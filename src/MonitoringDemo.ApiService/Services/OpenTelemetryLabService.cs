using System.Collections.Concurrent;
using System.Diagnostics;
using System.Diagnostics.Metrics;
using System.Reflection;
using MonitoringDemo.ApiService.Telemetry;

namespace MonitoringDemo.ApiService.Services;

public sealed class OpenTelemetryLabService
{
    private const int MaximumSamples = 5_000;
    private static readonly string[] Operations = ["checkout", "catalog", "payment", "fulfillment"];
    private static readonly string[] Methods = ["GET", "POST", "POST", "PUT"];

    private readonly AppActivitySource _activitySource;
    private readonly ILogger<OpenTelemetryLabService> _logger;
    private readonly Counter<long> _requestCounter;
    private readonly Histogram<double> _durationHistogram;
    private readonly ConcurrentQueue<OpenTelemetrySample> _samples = new();
    private readonly IReadOnlyList<TelemetryResourceAttribute> _resourceAttributes;
    private int _sampleCount;
    private int _seedRun;
    private int _inFlight;

    public OpenTelemetryLabService(
        AppActivitySource activitySource,
        IMeterFactory meterFactory,
        IHostEnvironment environment,
        ILogger<OpenTelemetryLabService> logger)
    {
        _activitySource = activitySource;
        _logger = logger;

        var meter = meterFactory.Create(TelemetryConstants.MeterName);
        _requestCounter = meter.CreateCounter<long>(
            "otel_demo_requests_total",
            unit: "{request}",
            description: "Requests generated by the OpenTelemetry learning lab");
        _durationHistogram = meter.CreateHistogram<double>(
            "otel_demo_duration_ms",
            unit: "ms",
            description: "Duration of seeded OpenTelemetry learning-lab operations");
        meter.CreateObservableGauge(
            "otel_demo_in_flight",
            () => Volatile.Read(ref _inFlight),
            unit: "{request}",
            description: "OpenTelemetry learning-lab operations currently in flight");

        _resourceAttributes =
        [
            new("service.name", TelemetryConstants.ServiceName, "Configured by ResourceBuilder.AddService"),
            new("service.version", Assembly.GetExecutingAssembly().GetName().Version?.ToString() ?? "1.0.0", "Application assembly version"),
            new("service.instance.id", $"{Environment.MachineName}-{Environment.ProcessId}", "Unique running process"),
            new("deployment.environment.name", environment.EnvironmentName, "Hosting environment")
        ];
    }

    public OpenTelemetrySeedResult Seed(int requestedCount)
    {
        int count = Math.Clamp(requestedCount, 1, 500);
        int run = Interlocked.Increment(ref _seedRun);
        var random = new Random(20260927 + run);
        var now = DateTimeOffset.UtcNow;
        string? firstTraceId = null;

        for (int index = 0; index < count; index++)
        {
            string operation = Operations[(index + run) % Operations.Length];
            string method = Methods[(index + run) % Methods.Length];
            bool failed = (index + run) % 9 == 0;
            double duration = CreateDuration(random, failed);
            var observedAt = now.AddSeconds(-random.Next(0, 30 * 60));
            string status = failed ? "Error" : "Ok";

            Interlocked.Increment(ref _inFlight);
            try
            {
                var rootTags = new ActivityTagsCollection
                {
                    { "demo.seed", true },
                    { "demo.operation", operation },
                    { "http.request.method", method },
                    { "url.path", $"/demo/{operation}" },
                    { "server.address", "monitoring-demo" },
                    { "http.response.status_code", failed ? 500 : 200 }
                };

                using var root = _activitySource.Source.StartActivity(
                    $"{method} /demo/{operation}",
                    ActivityKind.Server,
                    default(ActivityContext),
                    rootTags);
                firstTraceId ??= root?.TraceId.ToString();

                using (var child = _activitySource.Source.StartActivity(
                    $"{operation}.process",
                    ActivityKind.Internal,
                    Activity.Current?.Context ?? default,
                    new ActivityTagsCollection
                    {
                        { "demo.instrumentation", "manual" },
                        { "code.function.name", "OpenTelemetryLabService.Seed" }
                    }))
                {
                    child?.AddEvent(new ActivityEvent(
                        "demo.processing.completed",
                        tags: new ActivityTagsCollection { { "demo.duration_ms", duration } }));
                    child?.SetStatus(failed ? ActivityStatusCode.Error : ActivityStatusCode.Ok);
                }

                root?.SetStatus(
                    failed ? ActivityStatusCode.Error : ActivityStatusCode.Ok,
                    failed ? "Seeded demonstration failure" : null);

                var tags = new TagList
                {
                    { "demo.operation", operation },
                    { "http.request.method", method }
                };
                if (failed) tags.Add("error.type", "seeded_failure");
                _requestCounter.Add(1, tags);
                _durationHistogram.Record(duration, tags);

                if (failed)
                {
                    _logger.LogWarning(
                        "OpenTelemetry seed operation {Operation} failed after {DurationMilliseconds} ms in run {SeedRun}",
                        operation,
                        duration,
                        run);
                }
                else
                {
                    _logger.LogInformation(
                        "OpenTelemetry seed operation {Operation} completed in {DurationMilliseconds} ms in run {SeedRun}",
                        operation,
                        duration,
                        run);
                }

                AddSample(new OpenTelemetrySample(observedAt, operation, status, duration, 2, 2, 1));
            }
            finally
            {
                Interlocked.Decrement(ref _inFlight);
            }
        }

        return new OpenTelemetrySeedResult(count, run, firstTraceId, GetAnalytics(60));
    }

    public OpenTelemetryOverview GetOverview(int requestedWindowMinutes)
    {
        int windowMinutes = Math.Clamp(requestedWindowMinutes, 5, 240);
        return new OpenTelemetryOverview(
            DateTimeOffset.UtcNow,
            windowMinutes,
            GetAnalytics(windowMinutes),
            Architecture,
            ApiAndSdk,
            Instrumentation,
            _resourceAttributes,
            SemanticConventions,
            SignalComponents,
            Propagators);
    }

    private OpenTelemetryAnalytics GetAnalytics(int windowMinutes)
    {
        var cutoff = DateTimeOffset.UtcNow.AddMinutes(-windowMinutes);
        var samples = _samples
            .Where(sample => sample.Timestamp >= cutoff)
            .OrderBy(sample => sample.Timestamp)
            .ToArray();
        var durations = samples.Select(sample => sample.DurationMilliseconds).Order().ToArray();
        var timeline = samples
            .GroupBy(sample => new DateTimeOffset(
                sample.Timestamp.Year,
                sample.Timestamp.Month,
                sample.Timestamp.Day,
                sample.Timestamp.Hour,
                sample.Timestamp.Minute,
                0,
                TimeSpan.Zero))
            .Select(group => new OpenTelemetryTimelinePoint(
                group.Key,
                group.Sum(item => item.SpanCount),
                group.Sum(item => item.MetricPointCount),
                group.Sum(item => item.LogRecordCount),
                group.Count(item => item.Status == "Error")))
            .ToArray();
        var operations = samples
            .GroupBy(sample => sample.Operation)
            .OrderBy(group => group.Key)
            .Select(group => new OpenTelemetryOperationAnalytics(
                group.Key,
                group.Count(),
                group.Count(item => item.Status == "Error"),
                Math.Round(group.Average(item => item.DurationMilliseconds), 2)))
            .ToArray();

        return new OpenTelemetryAnalytics(
            samples.Length,
            samples.Sum(sample => sample.SpanCount),
            samples.Sum(sample => sample.MetricPointCount),
            samples.Sum(sample => sample.LogRecordCount),
            samples.Count(sample => sample.Status == "Error"),
            durations.Length == 0 ? 0 : Math.Round(durations.Average(), 2),
            Percentile(durations, 0.95),
            timeline,
            operations);
    }

    private void AddSample(OpenTelemetrySample sample)
    {
        _samples.Enqueue(sample);
        int count = Interlocked.Increment(ref _sampleCount);
        while (count > MaximumSamples && _samples.TryDequeue(out _))
        {
            count = Interlocked.Decrement(ref _sampleCount);
        }
    }

    private static double CreateDuration(Random random, bool failed) =>
        failed ? random.Next(650, 1_800) : random.Next(35, 620);

    private static double Percentile(double[] values, double percentile)
    {
        if (values.Length == 0) return 0;
        int index = (int)Math.Ceiling(values.Length * percentile) - 1;
        return Math.Round(values[Math.Clamp(index, 0, values.Length - 1)], 2);
    }

